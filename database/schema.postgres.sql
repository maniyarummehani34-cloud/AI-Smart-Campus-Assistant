-- ============================================================================
-- 6. TIMETABLE OVERLAP PREVENTION TRIGGERS (INSERT & UPDATE)
-- ============================================================================

CREATE OR REPLACE FUNCTION fn_timetable_no_overlap()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF NEW.end_time <= NEW.start_time THEN
        RAISE EXCEPTION 'Timetable error: end_time must be later than start_time.'
            USING ERRCODE = 'P0001';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM timetable
        WHERE (TG_OP <> 'UPDATE' OR id <> NEW.id)
          AND day_of_week = NEW.day_of_week
          AND classroom = NEW.classroom
          AND NEW.start_time < end_time
          AND NEW.end_time > start_time
    ) THEN
        RAISE EXCEPTION 'Timetable conflict: classroom is already booked during this time slot.'
            USING ERRCODE = 'P0001';
    END IF;

    IF NEW.faculty_id IS NOT NULL AND EXISTS (
        SELECT 1
        FROM timetable
        WHERE (TG_OP <> 'UPDATE' OR id <> NEW.id)
          AND day_of_week = NEW.day_of_week
          AND faculty_id = NEW.faculty_id
          AND NEW.start_time < end_time
          AND NEW.end_time > start_time
    ) THEN
        RAISE EXCEPTION 'Timetable conflict: faculty member is already scheduled during this time slot.'
            USING ERRCODE = 'P0001';
    END IF;

    IF EXISTS (
        SELECT 1
        FROM timetable
        WHERE (TG_OP <> 'UPDATE' OR id <> NEW.id)
          AND day_of_week = NEW.day_of_week
          AND department = NEW.department
          AND semester = NEW.semester
          AND section = NEW.section
          AND NEW.start_time < end_time
          AND NEW.end_time > start_time
    ) THEN
        RAISE EXCEPTION 'Timetable conflict: this department/semester/section already has a class during this time slot.'
            USING ERRCODE = 'P0001';
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_timetable_no_overlap_insert ON timetable;
CREATE TRIGGER trg_timetable_no_overlap_insert
    BEFORE INSERT ON timetable
    FOR EACH ROW
    EXECUTE FUNCTION fn_timetable_no_overlap();

DROP TRIGGER IF EXISTS trg_timetable_no_overlap_update ON timetable;
CREATE TRIGGER trg_timetable_no_overlap_update
    BEFORE UPDATE ON timetable
    FOR EACH ROW
    EXECUTE FUNCTION fn_timetable_no_overlap();
