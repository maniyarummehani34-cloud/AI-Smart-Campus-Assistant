-- ============================================================================
-- AI-Powered Smart Campus Assistant — PostgreSQL Schema (Phase 1)
-- Target Database: campus_assistant_pg
-- Source Reference: database/backups/campus_assistant_db_v2_deploy_backup.sql
--
-- Notes:
--   - Preserves all 14 tables, original column names, defaults, NULL/NOT NULL
--     rules, 20 foreign keys, 15 unique constraints, 9 domain CHECK constraints,
--     20 ENUM-equivalent CHECK constraints, 38 secondary indexes, 13 updated_at
--     triggers, and both timetable overlap triggers.
--   - Tables are ordered in strict parent-before-child foreign-key order.
--   - Uses INTEGER GENERATED BY DEFAULT AS IDENTITY so existing MySQL IDs can
--     be migrated verbatim and identity sequences synchronized via setval().
--   - Uses BOOLEAN for is_demo columns and TIMESTAMP for DATETIME/TIMESTAMP.
